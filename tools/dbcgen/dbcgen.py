#!/usr/bin/env python3
"""
UBC Baja DBC compiler.

Generates the regular cantools C source for each DBC.
Appends one struct per signal group (SIG_GROUP_) and a helper that copies that group into
its message struct.

Usage:
    python tools/dbcgen/dbcgen.py                    # every lib/dbc/*.dbc, in place
    python tools/dbcgen/dbcgen.py path/to/my.dbc -o out/
"""

import argparse
import sys
from pathlib import Path

import cantools
from cantools.database.can.c_source import (
    CodeGenMessage,
    _generate_signal,
    camel_to_snake_case,
    generate,
)

DEFAULT_DBC_DIR = Path(__file__).resolve().parents[2] / 'lib' / 'dbc'

# Payload sizes a CAN FD frame can carry (classic CAN is 0..8).
CANFD_LENGTHS = (0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 16, 20, 24, 32, 48, 64)

HEADER_BANNER = '''\
/*
 * Signal group structs, generated by dbcgen from the SIG_GROUP_ entries.
 *
 * Each group is plain data with no locking. Guard shared instances yourself
 * and use the _to_msg() helpers to copy a group into its message before
 * packing.
 */

'''

SOURCE_BANNER = '''\
/* Signal group helpers, generated by dbcgen from the SIG_GROUP_ entries. */

'''

GROUP_STRUCT_FMT = '''\
/**
 * Signals in signal group {group} of message {message}.
 *
 * All signal values are as on the CAN bus.
 */
struct {db}_{msg}_{grp}_t {{
{members}
}};
'''

TO_MSG_DECLARATION_FMT = '''\
/**
 * Copy signal group {group} into message {message}.
 *
 * Only the group's signals are written, the rest of dst_p is left as is.
 *
 * @param[in] src_p Group to copy from.
 * @param[out] dst_p Message to copy into.
 */
void {db}_{msg}_{grp}_to_msg(
    const struct {db}_{msg}_{grp}_t *src_p,
    struct {db}_{msg}_t *dst_p);
'''

TO_MSG_DEFINITION_FMT = '''\
void {db}_{msg}_{grp}_to_msg(
    const struct {db}_{msg}_{grp}_t *src_p,
    struct {db}_{msg}_t *dst_p)
{{
{assignments}
}}
'''


def validate(database):
    """Return a list of problems that would make the generated code wrong."""
    errors = []
    message_names = {camel_to_snake_case(m.name) for m in database.messages}

    for message in database.messages:
        if message.length not in CANFD_LENGTHS:
            errors.append(f'{message.name}: length {message.length} is not a '
                          f'valid CAN/CAN FD payload size {CANFD_LENGTHS}')

        groups = message.signal_groups or []

        if not groups:
            continue

        msg = camel_to_snake_case(message.name)
        group_names = set()
        owner = {}

        for group in groups:
            grp = camel_to_snake_case(group.name)

            if grp in group_names:
                errors.append(f'{message.name}: signal group {group.name} is defined twice')

            group_names.add(grp)

            if f'{msg}_{grp}' in message_names:
                errors.append(f'{message.name}: struct for signal group {group.name} '
                              f'collides with message {msg}_{grp}')

            for name in group.signal_names:
                if name not in {s.name for s in message.signals}:
                    errors.append(f'{message.name}: signal group {group.name} '
                                  f'references unknown signal {name}')
                elif name in owner:
                    errors.append(f'{message.name}: signal {name} is in both '
                                  f'{owner[name]} and {group.name}')
                else:
                    owner[name] = group.name

        for signal in message.signals:
            if signal.name not in owner:
                errors.append(f'{message.name}: signal {signal.name} is not in any signal group')

    return errors


def generate_groups(database, database_name):
    """Return (header declarations, source definitions) for all signal groups."""
    declarations = []
    definitions = []

    for message in database.messages:
        cg_message = CodeGenMessage(message)

        for group in message.signal_groups or []:
            cg_signals = [cg_message.get_signal_by_name(name) for name in group.signal_names]
            names = {
                'db': database_name,
                'msg': cg_message.snake_name,
                'grp': camel_to_snake_case(group.name),
                'group': group.name,
                'message': message.name,
            }
            members = '\n\n'.join(_generate_signal(cg_signal, False) for cg_signal in cg_signals)
            assignments = '\n'.join(f'    dst_p->{s.snake_name} = src_p->{s.snake_name};'
                                    for s in cg_signals)

            declarations.append(GROUP_STRUCT_FMT.format(members=members, **names))
            declarations.append(TO_MSG_DECLARATION_FMT.format(**names))
            definitions.append(TO_MSG_DEFINITION_FMT.format(assignments=assignments, **names))

    return declarations, definitions


def compile_dbc(dbc_path, output_dir):
    database = cantools.database.load_file(dbc_path)
    errors = validate(database)

    if errors:
        raise ValueError('\n'.join(f'  {e}' for e in errors))

    database_name = camel_to_snake_case(dbc_path.stem)
    header_name = f'{database_name}.h'
    source_name = f'{database_name}.c'
    header, source, _, _ = generate(database,
                                    database_name,
                                    header_name,
                                    source_name,
                                    f'{database_name}_fuzzer.c')
    declarations, definitions = generate_groups(database, database_name)

    if declarations:
        # Slot the group code in before the header's closing extern "C" / include guard.
        end = header.rfind('#ifdef __cplusplus')

        if end == -1:
            raise RuntimeError(f'unexpected cantools header layout for {dbc_path.name}')

        header = header[:end] + HEADER_BANNER + '\n'.join(declarations) + '\n' + header[end:]
        source = source + '\n' + SOURCE_BANNER + '\n'.join(definitions)

    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / header_name).write_text(header)
    (output_dir / source_name).write_text(source)
    groups = len(definitions)
    print(f'{dbc_path.name}: wrote {header_name} and {source_name} ({groups} signal groups)')


def main():
    parser = argparse.ArgumentParser(description='Generate C source plus signal group structs from DBC files.')
    parser.add_argument('dbc_files', nargs='*', type=Path,
                        help=f'DBC files to compile (default: every .dbc in {DEFAULT_DBC_DIR})')
    parser.add_argument('-o', '--output-directory', type=Path,
                        help='where to write the .c/.h files (default: next to each DBC)')
    args = parser.parse_args()

    dbc_files = args.dbc_files or sorted(DEFAULT_DBC_DIR.glob('*.dbc'))
    failed = False

    for dbc_path in dbc_files:
        try:
            compile_dbc(dbc_path, args.output_directory or dbc_path.parent)
        except (ValueError, cantools.database.Error) as e:
            print(f'error: {dbc_path.name} was not generated:\n{e}', file=sys.stderr)
            failed = True

    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
